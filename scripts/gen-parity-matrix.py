#!/usr/bin/env python3
"""Generate the parity matrix from the conformance results of the language packages (ADR-001 2.7).

Each package's runner writes `<package>/target/conformance-results.gram`, one `Result` node per case:

    (case-id:Result {language: rust, status: passed})
    (case-id:Result {language: rust, status: skipped, reason: "why"})

The matrix lists every case of `conformance/*.gram` against every language. It exits with 1 when a
case failed or has no result (an unreviewed gap), and 0 otherwise; a skipped case is a visible,
accepted gap.

    scripts/gen-parity-matrix.py [--out docs/parity.md] [language=path ...]
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RESULTS = {
    "rust": ROOT / "rust" / "target" / "conformance-results.gram",
    "typescript": ROOT / "typescript" / "target" / "conformance-results.gram",
    "python": ROOT / "python" / "target" / "conformance-results.gram",
    "go": ROOT / "go" / "conformance" / "target" / "conformance-results.gram",
    "swift": ROOT / "swift" / "Tests" / "target" / "conformance-results.gram",
}
CASE_FILES = ("values.gram", "text.gram", "tags.gram", "mappings.gram")
STATUSES = ("passed", "failed", "skipped", "not-applicable")
SYMBOL = {"passed": "✅", "failed": "❌", "skipped": "⏭️", "not-applicable": "—", "missing": "❓"}
CASE_LINE = re.compile(r"^\((?P<id>[\w-]+):(?P<kind>\w+Case) ")
RESULT_LINE = re.compile(r"^\((?P<id>[\w-]+):Result \{(?P<props>.*)\}\)$")


def read_cases(corpus):
    """Return [(case id, case kind)] in corpus order."""
    cases = []
    for name in CASE_FILES:
        for line in (corpus / name).read_text(encoding="utf-8").splitlines():
            m = CASE_LINE.match(line)
            if m:
                cases.append((m.group("id"), m.group("kind")))
    return cases


def read_results(path):
    """Return {case id: (status, reason or None)} from one results file."""
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = RESULT_LINE.match(line)
        if not m:
            continue
        props = m.group("props")
        status = re.search(r"status: ([\w-]+)", props)
        reason = re.search(r'reason: ("(?:[^"\\]|\\.)*")', props)
        if not status or status.group(1) not in STATUSES:
            raise SystemExit(f"{path}: unreadable result for {m.group('id')}")
        out[m.group("id")] = (status.group(1), json.loads(reason.group(1)) if reason else None)
    return out


def build(cases, results):
    """Return {(case id, language): (status, reason)} with 'missing' for absent results."""
    cells = {}
    for cid, _ in cases:
        for lang, res in results.items():
            cells[(cid, lang)] = res.get(cid, ("missing", None))
    return cells


def render(cases, results, cells):
    langs = list(results)
    kinds = sorted({k for _, k in cases})
    lines = [
        "# Parity matrix",
        "",
        "Generated by `scripts/gen-parity-matrix.py` from the conformance results of each language package",
        "(ADR-001); do not edit. A skipped case is a declared gap with a reason; a missing one is a defect.",
        "",
        "## Summary",
        "",
        "| Language | " + " | ".join(f"{SYMBOL[s]} {s}" for s in (*STATUSES, "missing")) + " |",
        "|---|" + "---|" * (len(STATUSES) + 1),
    ]
    for lang in langs:
        counts = Counter(cells[(cid, lang)][0] for cid, _ in cases)
        lines.append(f"| {lang} | " + " | ".join(str(counts.get(s, 0)) for s in (*STATUSES, "missing")) + " |")
    lines += ["", "## By kind of case", "", "| Case kind | Cases | " + " | ".join(langs) + " |", "|---|---|" + "---|" * len(langs)]
    for kind in kinds:
        ids = [cid for cid, k in cases if k == kind]
        row = []
        for lang in langs:
            passed = sum(cells[(cid, lang)][0] == "passed" for cid in ids)
            na = sum(cells[(cid, lang)][0] == "not-applicable" for cid in ids)
            row.append(f"{passed}/{len(ids) - na}")
        lines.append(f"| {kind} | {len(ids)} | " + " | ".join(row) + " |")
    gaps = [(cid, lang, *cells[(cid, lang)]) for cid, _ in cases for lang in langs
            if cells[(cid, lang)][0] in ("failed", "skipped", "missing")]
    lines += ["", "## Gaps", ""]
    if gaps:
        lines += ["| Case | Language | Status | Reason |", "|---|---|---|---|"]
        for cid, lang, status, reason in gaps:
            lines.append(f"| {cid} | {lang} | {SYMBOL[status]} {status} | {reason or ''} |")
    else:
        lines.append("None: every case passes or does not apply in every language.")
    lines += ["", "## All cases", "", "| Case | Kind | " + " | ".join(langs) + " |", "|---|---|" + "---|" * len(langs)]
    for cid, kind in cases:
        lines.append(f"| {cid} | {kind} | " + " | ".join(SYMBOL[cells[(cid, lang)][0]] for lang in langs) + " |")
    return "\n".join(lines) + "\n"


def main(argv):
    out = None
    paths = {}
    args = list(argv)
    while args:
        a = args.pop(0)
        if a == "--out":
            out = Path(args.pop(0))
        elif "=" in a:
            lang, _, p = a.partition("=")
            paths[lang] = Path(p)
        else:
            raise SystemExit(f"unknown argument {a}")
    paths = paths or DEFAULT_RESULTS
    cases = read_cases(ROOT / "conformance")
    results = {}
    for lang, p in paths.items():
        if not p.exists():
            raise SystemExit(f"no results for {lang} at {p}; run its conformance tests first")
        results[lang] = read_results(p)
    cells = build(cases, results)
    text = render(cases, results, cells)
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    bad = [(c, l, s) for (c, l), (s, _) in cells.items() if s in ("failed", "missing")]
    for c, l, s in bad:
        print(f"{s}: {c} in {l}", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
