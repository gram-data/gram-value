"""The data values of the gram notation.

``gram-value`` models every value gram can write (integers, decimals, booleans, strings, tagged
strings, ranges, measurements, arrays and maps), compares them, writes each as canonical gram
text, interprets the ten known tags, and maps values to Python values. It does not parse:
`tree-sitter-gram <https://github.com/gram-data/tree-sitter-gram>`_ does. The rules are in
``spec/`` of the repository; the decisions are ADR-002 to ADR-006 under ``design/adr/``.
"""

